/** Host-side templates: index.js and the optional SQLite store. */
import { fill, jsString, TEMPLATE_BASELINE, TEMPLATE_VERSION } from './meta.js'

const HOST_TEMPLATE = `/** {{titleEn}} host plugin. Generated by dsh-plugin-devkit template {{templateVersion}} (baseline: {{baseline}}). */
{{imports}}
export const name = '{{slug}}'
export const inject = [{{injectList}}]

export function apply(ctx, config = {}) {
{{body}}
}
`

export function hostIndex(form) {
  const { features } = form
  const imports = []
  if (features.sqlite) {
    imports.push("import { join } from 'node:path'", "import { Store } from './lib/store.js'")
  }
  const injectNames = [
    ...(features.httpApi ? ['connection'] : []),
    ...(features.sqlite ? ['profileContext'] : []),
    ...(features.timer ? ['timer'] : []),
  ]
  const body = []
  if (features.sqlite) {
    body.push(`  const store = new Store(join(ctx.profileContext.dir, '${form.slug}', '${form.slug}.sqlite'))`)
  }
  if (features.httpApi || features.timer) {
    body.push('  const state = { ticks: 0 }')
  }
  if (features.httpApi) {
    body.push(`  const disposeRoute = ctx.connection.fetch.register({
    path: '${form.apiBase}/hello',
    methods: ['GET'],
    requestBody: 'buffered',
    fetch: async () => new Response(JSON.stringify({
      plugin: '${form.slug}',
      message: ${jsString(`Hello from ${form.titleEn}`)},${features.timer ? '\n      ticks: state.ticks,' : ''}
      time: Date.now(),
    }), { headers: { 'content-type': 'application/json; charset=utf-8', 'cache-control': 'no-store' } }),
  })`)
  }
  if (features.timer) {
    body.push(`  // Sample periodic task: the cordis timer service disposes it with the plugin.
  ctx.interval(() => { state.ticks += 1 }, 60_000)`)
  }
  const disposals = [
    ...(features.httpApi ? ['    disposeRoute()'] : []),
    ...(features.sqlite ? ['    store.close()'] : []),
  ]
  if (disposals.length > 0) {
    body.push(`  ctx.effect(() => () => {
${disposals.join('\n')}
  }, '${form.slug}: resources')`)
  }
  if (body.length === 0) {
    body.push('  // Add host logic here: services, events, HTTP routes (see README).')
  }
  return fill(HOST_TEMPLATE, {
    titleEn: form.titleEn,
    templateVersion: TEMPLATE_VERSION,
    baseline: TEMPLATE_BASELINE,
    imports: imports.length > 0 ? `\n${imports.join('\n')}\n` : '',
    slug: form.slug,
    injectList: injectNames.map(name => `'${name}'`).join(', '),
    body: body.join('\n\n'),
  })
}

const STORE_TEMPLATE = `import { mkdirSync } from 'node:fs'
import { dirname } from 'node:path'
import { DatabaseSync } from 'node:sqlite'

/** Minimal SQLite store (WAL) for {{titleEn}}. Generated by dsh-plugin-devkit template {{templateVersion}}. */
export class Store {
  constructor(filename) {
    mkdirSync(dirname(filename), { recursive: true })
    this.db = new DatabaseSync(filename)
    this.db.exec('PRAGMA journal_mode = WAL; PRAGMA busy_timeout = 5000;')
    this.db.exec(\`
      CREATE TABLE IF NOT EXISTS meta (
        key TEXT PRIMARY KEY,
        value TEXT NOT NULL
      ) STRICT;
      CREATE TABLE IF NOT EXISTS notes (
        id INTEGER PRIMARY KEY AUTOINCREMENT,
        text TEXT NOT NULL,
        created_at INTEGER NOT NULL
      ) STRICT;
    \`)
    this.db.prepare('INSERT OR IGNORE INTO meta(key, value) VALUES (?, ?)').run('installed_at', String(Date.now()))
    this.insertNote = this.db.prepare('INSERT INTO notes(text, created_at) VALUES (?, ?)')
    this.selectNotes = this.db.prepare('SELECT id, text, created_at FROM notes ORDER BY id DESC LIMIT ?')
  }

  addNote(text) {
    const result = this.insertNote.run(String(text), Date.now())
    return Number(result.lastInsertRowid)
  }

  listNotes(limit = 50) {
    return this.selectNotes.all(Math.max(1, Math.min(200, limit)))
  }

  close() {
    this.db.close()
  }
}
`

export function storeLib(form) {
  return fill(STORE_TEMPLATE, { titleEn: form.titleEn, templateVersion: TEMPLATE_VERSION })
}