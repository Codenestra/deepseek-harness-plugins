const STORE_TESTS = `
test('the store round-trips notes', () => {
  const dir = mkdtempSync(join(tmpdir(), '{{slug}}-store-'))
  const store = new Store(join(dir, 'store.sqlite'))
  try {
    const id = store.addNote('hello')
    assert.ok(id >= 1)
    const notes = store.listNotes()
    assert.equal(notes.length, 1)
    assert.equal(notes[0].text, 'hello')
  } finally {
    store.close()
    rmSync(dir, { recursive: true, force: true })
  }
})
`

function featureList(form, lang) {
  const zh = {
    httpApi: '示例 HTTP API（`GET {{apiBase}}/hello`，Connection Fetch 注册）',
    sqlite: 'SQLite 存储（`node:sqlite`，WAL，`<profile>/{{slug}}/{{slug}}.sqlite`）',
    timer: '定时任务示例（cordis timer 服务，`ctx.interval`，随插件自动释放）',
    settings: '设置页（`settings.section` slot，示例开关本地保存）',
  }
  const en = {
    httpApi: 'Sample HTTP API (`GET {{apiBase}}/hello`, registered via Connection Fetch)',
    sqlite: 'SQLite storage (`node:sqlite`, WAL, `<profile>/{{slug}}/{{slug}}.sqlite`)',
    timer: 'Sample periodic task (cordis timer service, `ctx.interval`, auto-disposed)',
    settings: 'Settings page (`settings.section` slot, sample toggle stored locally)',
  }
  const table = lang === 'zh' ? zh : en
  const enabled = Object.entries(form.features).filter(([, on]) => on).map(([key]) => table[key])
  const base = lang === 'zh'
    ? ['侧边栏面板（`sidebar.panellist`，order {{order}}）+ 主视图（`main`）', '中英双语 locale']
    : ['Sidebar panel (`sidebar.panellist`, order {{order}}) + main view (`main`)', 'Bilingual locale (zh/en)']
  return [...base, ...enabled].map(line => `- ${fill(line, form)}`).join('\n')
}

function structure(form) {
  const lines = [
    'package.json',
    'cordis.patch.yml',
    'index.js',
    'client.js',
    ...(form.features.sqlite ? ['lib/store.js'] : []),
    'locale/zh.json',
    'locale/en.json',
    'icon.svg',
    'tests/smoke.test.mjs',
    'README.md',
    'README.zh.md',
  ]
  return lines.join('\n')
}

