/** Client bundle template: build-free React.createElement panel. */
import { fill, jsString } from './meta.js'

const CLIENT_TEMPLATE = `(() => {
  const PACKAGE_ID = '{{packageName}}'
  const PANEL_ID = '{{slug}}'
{{apiConst}}
  const COPY = {
    zh: {
      panel: {{titleZhJs}}, title: {{titleZhJs}},
      subtitle: '由 dsh-plugin-devkit 脚手架生成的插件面板',
      callApi: '调用示例 API', loading: '请求中…', failed: '请求失败',
      devHint: '在 index.js 中添加宿主逻辑，在 client.js 中扩展此面板。',
      settingsHint: '示例设置项（保存在浏览器本地）', toggle: '启用示例开关',
    },
    en: {
      panel: {{titleEnJs}}, title: {{titleEnJs}},
      subtitle: 'Plugin panel generated by the dsh-plugin-devkit scaffold',
      callApi: 'Call sample API', loading: 'Loading…', failed: 'Request failed',
      devHint: 'Add host logic in index.js and extend this panel in client.js.',
      settingsHint: 'Sample setting (stored locally in the browser)', toggle: 'Enable sample toggle',
    },
  }

  function localeKey() {
    const language = document.documentElement.lang || navigator.language || 'en'
    return language.toLowerCase().startsWith('zh') ? 'zh' : 'en'
  }

  const STYLE = \`
  .{{cssPrefix}}-page, .{{cssPrefix}}-page * { box-sizing: border-box; }
  .{{cssPrefix}}-page { height:100%; min-width:0; overflow:auto; padding:calc(26px + var(--dsh-frame-top-clearance, 0px)) 28px 48px; background:var(--dsw-alias-bg-base); color:var(--dsw-alias-label-primary); font-family:var(--dsw-font-family, inherit); }
  .{{cssPrefix}}-shell { width:min(960px, 100%); margin:0 auto; }
  .{{cssPrefix}}-title { margin:0; font-size:26px; line-height:1.2; letter-spacing:-.02em; }
  .{{cssPrefix}}-subtitle { margin:8px 0 20px; color:var(--dsw-alias-label-secondary); font-size:13px; }
  .{{cssPrefix}}-card { display:grid; gap:12px; justify-items:start; padding:16px; border:0.5px solid var(--dsw-alias-border-l3); border-radius:var(--dsw-radius-lg, 14px); background:var(--dsw-alias-bg-layer-1); }
  .{{cssPrefix}}-hint { margin:0; color:var(--dsw-alias-label-tertiary); font-size:12px; line-height:1.5; }
  .{{cssPrefix}}-button { min-height:36px; padding:0 14px; border:0.5px solid transparent; border-radius:var(--dsw-radius-md, 10px); background:var(--dsw-alias-brand-primary); color:var(--dsw-alias-label-on-color, white); cursor:pointer; font:inherit; font-size:12px; font-weight:600; }
  .{{cssPrefix}}-button:disabled { opacity:.55; cursor:not-allowed; }
  .{{cssPrefix}}-error { margin:0; color:var(--dsw-alias-state-error); font-size:12px; }
  .{{cssPrefix}}-pre { margin:0; padding:12px; width:100%; overflow:auto; border-radius:var(--dsw-radius-md, 10px); background:var(--dsw-alias-bg-layer-2); font-size:11px; line-height:1.5; }
  .{{cssPrefix}}-settings { display:grid; gap:10px; font-size:13px; }
  .{{cssPrefix}}-toggle { display:inline-flex; align-items:center; gap:8px; cursor:pointer; }
  \`

  window.__ModuleLoader__.load({
    id: PACKAGE_ID,
    factory(require) {
      const React = require('react')
      const { {{hookList}} } = React
      const h = React.createElement

      function tcopy() { return COPY[localeKey()] }

      function Icon({ size = 20 }) {
        return h('svg', {
          width: size, height: size, viewBox: '0 0 24 24', fill: 'none',
          stroke: 'currentColor', strokeWidth: 1.7, strokeLinecap: 'round', strokeLinejoin: 'round', 'aria-hidden': 'true',
        },
        h('path', { d: 'M12 3l7 4v10l-7 4-7-4V7l7-4z' }),
        h('path', { d: 'M12 12l7-4M12 12v9M12 12L5 8' }))
      }

      function Page() {
        const c = tcopy()
{{pageBody}}
        return h('div', { className: '{{cssPrefix}}-page' },
          h('div', { className: '{{cssPrefix}}-shell' },
            h('h1', { className: '{{cssPrefix}}-title' }, c.title),
            h('p', { className: '{{cssPrefix}}-subtitle' }, c.subtitle),
{{pageSection}}
          ))
      }
{{settingsComponent}}
      return {
        inject: ['slots', 'locale'],
        apply(ctx) {
          ctx.effect(() => {
            const style = document.createElement('style')
            style.dataset.plugin = PACKAGE_ID
            style.textContent = STYLE
            document.head.append(style)
            return () => style.remove()
          }, '{{slug}}: styles')
          ctx.effect(() => ctx.locale.register('{{camel}}', {
            zh: { panel: COPY.zh.panel },
            en: { panel: COPY.en.panel },
          }), '{{slug}}: locale')
          const label = ctx.locale.bind('{{camel}}')
          ctx.slots.inject('main', () => ctx.slots.register({
            name: 'main', key: PANEL_ID, locale: '{{camel}}',
          }, Page))
          ctx.slots.inject('sidebar.panellist', () => ctx.slots.register({
            name: 'sidebar.panellist', id: PANEL_ID, order: {{order}},
            label: () => label('panel'), locale: '{{camel}}',
          }, Icon)){{settingsRegistration}}
        },
      }
    },
  })
})()
`

const API_PAGE_BODY = `        const [state, setState] = useState({ phase: 'idle', data: null, error: '' })
        const callApi = () => {
          setState({ phase: 'loading', data: null, error: '' })
          fetch(API + '/hello', { headers: { accept: 'application/json' } }).then(async (response) => {
            const body = await response.json()
            if (!response.ok) throw new Error((body && body.error && body.error.message) || String(response.status))
            setState({ phase: 'ready', data: body, error: '' })
          }).catch((error) => setState({ phase: 'error', data: null, error: error instanceof Error ? error.message : String(error) }))
        }`

const API_PAGE_SECTION = `            h('section', { className: '{{cssPrefix}}-card' },
              h('button', { type: 'button', className: '{{cssPrefix}}-button', onClick: callApi, disabled: state.phase === 'loading' }, state.phase === 'loading' ? c.loading : c.callApi),
              state.phase === 'error' ? h('p', { className: '{{cssPrefix}}-error' }, c.failed + ': ' + state.error) : null,
              state.data ? h('pre', { className: '{{cssPrefix}}-pre' }, JSON.stringify(state.data, null, 2)) : null,
            ),`

const PLAIN_PAGE_SECTION = `            h('section', { className: '{{cssPrefix}}-card' },
              h('p', { className: '{{cssPrefix}}-hint' }, c.devHint),
            ),`

const SETTINGS_COMPONENT = `
      function Settings() {
        const c = tcopy()
        const [on, setOn] = useState(() => {
          try { return window.localStorage.getItem(PACKAGE_ID + '.demo') === '1' } catch (error) { return false }
        })
        useEffect(() => {
          try { window.localStorage.setItem(PACKAGE_ID + '.demo', on ? '1' : '0') } catch (error) { /* private mode */ }
        }, [on])
        return h('div', { className: '{{cssPrefix}}-settings' },
          h('p', { className: '{{cssPrefix}}-hint' }, c.settingsHint),
          h('label', { className: '{{cssPrefix}}-toggle' },
            h('input', { type: 'checkbox', checked: on, onChange: () => setOn(!on) }),
            c.toggle))
      }
`

const SETTINGS_REGISTRATION = `
          ctx.slots.inject('settings.section', () => ctx.slots.register({
            name: 'settings.section', id: PANEL_ID, order: {{order}},
            label: () => label('panel'), locale: '{{camel}}',
          }, Settings))`

export function clientBundle(form) {
  const vars = {
    packageName: form.packageName,
    slug: form.slug,
    camel: form.camel,
    cssPrefix: `gen-${form.slug}`,
    order: form.order,
    titleZhJs: jsString(form.titleZh),
    titleEnJs: jsString(form.titleEn),
    apiConst: form.features.httpApi ? `  const API = '${form.apiBase}'\n` : '',
    hookList: form.features.settings ? 'useEffect, useState' : 'useState',
    pageBody: form.features.httpApi ? API_PAGE_BODY : '',
    pageSection: fill(form.features.httpApi ? API_PAGE_SECTION : PLAIN_PAGE_SECTION, { cssPrefix: `gen-${form.slug}` }),
    settingsComponent: form.features.settings ? fill(SETTINGS_COMPONENT, { cssPrefix: `gen-${form.slug}` }) : '',
    settingsRegistration: form.features.settings ? fill(SETTINGS_REGISTRATION, { order: form.order, camel: form.camel }) : '',
  }
  return fill(CLIENT_TEMPLATE, vars)
}