/** Manifest templates: package.json, cordis.patch.yml, locale files, icon. */
import { TEMPLATE_BASELINE, TEMPLATE_VERSION } from './meta.js'

export function packageJson(form) {
  const manifest = {
    name: form.packageName,
    version: '0.1.0',
    description: `${form.titleEn} — a DeepSeek Harness plugin`,
    type: 'module',
    icon: './icon.svg',
    exports: {
      '.': './index.js',
      './client': './client.js',
      './package.json': './package.json',
      './locale/*.json': './locale/*.json',
      './lib/*': './lib/*',
    },
    files: [
      'client.js',
      'cordis.patch.yml',
      'icon.svg',
      'index.js',
      'lib/*.js',
      'locale/*.json',
      'README.md',
      'README.zh.md',
    ],
    scripts: {
      test: 'node --test ./tests/*.test.mjs',
      check: 'node --check index.js && node --check client.js && node --test ./tests/*.test.mjs',
    },
    engines: { node: '>=22.19.0' },
    peerDependencies: { '@deepseek-ai/cordis': '~4.0.4' },
    dsh: {
      bundle: { patch: './cordis.patch.yml' },
      client: { platform: 'web', inject: form.inject },
    },
  }
  return `${JSON.stringify(manifest, null, 2)}\n`
}

export function patchYml(form) {
  return `- insert:
    - id: ${form.panelId}
      name: '${form.packageName}'
      config: {}
`
}

export function localeFiles(form) {
  const zh = {
    panel: form.titleZh,
    title: form.titleZh,
    description: `${form.titleZh} —— 由 dsh-plugin-devkit 脚手架生成（模板 ${TEMPLATE_VERSION}，基线 ${TEMPLATE_BASELINE}）`,
  }
  const en = {
    panel: form.titleEn,
    title: form.titleEn,
    description: `${form.titleEn} — generated by the dsh-plugin-devkit scaffold (template ${TEMPLATE_VERSION}, baseline ${TEMPLATE_BASELINE})`,
  }
  return [
    { path: 'locale/zh.json', content: `${JSON.stringify(zh, null, 2)}\n` },
    { path: 'locale/en.json', content: `${JSON.stringify(en, null, 2)}\n` },
  ]
}

